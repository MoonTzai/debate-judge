function splitR3Revision(text) {
  const start = '<!--SC_REVISED_P2_START-->', end = '<!--SC_REVISED_P2_END-->';
  const a = text.indexOf(start), b = text.indexOf(end);
  if (a < 0 && b < 0) return { text, p2: null };
  if (a < 0 || b < a || text.indexOf(start, a + start.length) >= 0 || text.indexOf(end, b + end.length) >= 0)
    throw new Error('R3 的 P2 修订传输块不完整或重复；请保持语义判断并重发完整修订及 P3');
  const p2 = text.slice(a + start.length, b).trim();
  if (!p2) throw new Error('R3 的 P2 修订块为空；无修订时请省略块');
  return { text: (text.slice(0, a) + text.slice(b + end.length)).trim(), p2 };
}

function readReviewRequests(text, round) {
  let requests;
  if (round === 'R3') {
    const marker = '<!--ANALYSIS_REVIEW_REQUESTS';
    const a = text.indexOf(marker);
    if (a < 0) return [];
    const b = text.indexOf('-->', a);
    if (b < 0 || text.indexOf(marker, a + marker.length) >= 0) throw new Error('复核请求块不完整或重复');
    requests = JSON.parse(text.slice(a + marker.length, b).trim());
  } else if (round === 'R4.5') {
    let parsed;
    try { parsed = JSON.parse(String(text).trim().replace(/^```(?:json)?\s*/i,'').replace(/\s*```$/,'')); }
    catch (_) { return []; } // Normal R4.5 representation retry handles invalid JSON.
    requests = parsed.review_requests;
    if (requests == null) return [];
  } else return [];
  if (!Array.isArray(requests)) throw new Error('review_requests 必须是数组');
  const allowed = round === 'R3' ? ['R1','R2','R2.5'] : ['R1','R2','R2.5','R3'];
  for (const r of requests) if (!r || !allowed.includes(r.targetRound) || typeof r.issue !== 'string' || !r.issue.trim())
    throw new Error('复核请求需要可返回的 targetRound 和非空 issue；保持原语义并修正传输');
  return requests;
}

